"""Analysis API: recommendations, background training runs, results."""
from __future__ import annotations

import json
import threading
import traceback

from fastapi import APIRouter, HTTPException

from ..database import db, load_json, new_id, row_to_dict
from ..services.ml_engine import (MLInputError, run_anomaly_detection,
                                  run_clustering, train_supervised)
from ..services.recommender import recommend_analyses

router = APIRouter(prefix="/api", tags=["analysis"])


def _load_dataset(dataset_id: str):
    from .datasets import _load_df
    return _load_df(dataset_id)


@router.post("/datasets/{dataset_id}/analysis/suggest")
def suggest(dataset_id: str):
    from .datasets import get_dataset
    d = get_dataset(dataset_id)
    profile = d.get("profile") or {}
    return {"recommendations": recommend_analyses(profile, _load_dataset(dataset_id)),
            "suggested_target": profile.get("suggested_target")}


def _run_analysis_job(analysis_id: str, dataset_id: str, task: str, config: dict):
    try:
        from .datasets import _load_df
        with db() as conn:
            conn.execute("UPDATE analyses SET status='running', progress=10 WHERE id=?",
                         (analysis_id,))
        df = _load_df(dataset_id)
        result = None
        model_id = None
        from ..config import MODELS_DIR

        if task in ("classification", "regression"):
            result = train_supervised(
                df, task=task, target=config["target"],
                algorithm=config["algorithm"],
                feature_cols=config.get("feature_columns"),
                exclude_cols=config.get("exclude_columns"),
                test_size=config.get("test_size", 0.2),
                artifact_dir=MODELS_DIR, dataset_id=dataset_id)
            with db() as conn:
                model_id = new_id()
                conn.execute(
                    "INSERT INTO models (id, dataset_id, analysis_id, algorithm, "
                    "task_type, target_column, feature_columns_json, "
                    "preprocessing_json, metrics_json, artifact_path, train_rows, "
                    "test_rows) VALUES (?,?,?,?,?,?,?,?,?,?,?,?)",
                    (model_id, dataset_id, analysis_id, result["algorithm"], task,
                     result["target"], json.dumps(result["feature_columns"]),
                     json.dumps(result["preprocessing"]),
                     json.dumps(result["metrics"]),
                     result.get("artifact_path"), result["train_rows"],
                     result["test_rows"]))
        elif task == "clustering":
            result = run_clustering(
                df, algorithm=config["algorithm"],
                feature_cols=config.get("feature_columns"),
                exclude_cols=config.get("exclude_columns"),
                n_clusters=config.get("n_clusters", 3),
                dbscan_eps=config.get("dbscan_eps"),
                dbscan_min_samples=config.get("dbscan_min_samples", 5))
        elif task == "anomaly":
            result = run_anomaly_detection(
                df, feature_cols=config.get("feature_columns"),
                exclude_cols=config.get("exclude_columns"),
                contamination=config.get("contamination", 0.05),
                label_column=config.get("label_column"))
            with db() as conn:
                conn.execute(
                    "INSERT INTO anomalies (id, dataset_id, analysis_id, method, "
                    "params_json, n_rows, n_flagged, contamination, results_json) "
                    "VALUES (?,?,?,?,?,?,?,?,?)",
                    (new_id(), dataset_id, analysis_id, "isolation_forest",
                     json.dumps({"contamination": config.get("contamination", 0.05)}),
                     result["rows_scored"], result["n_flagged"],
                     config.get("contamination", 0.05), json.dumps(result)))
        else:
            raise MLInputError(f"Unsupported task '{task}'.")

        # persist findings generated by this analysis
        from ..services.decision_engine import generate_findings
        with db() as conn:
            name_row = conn.execute("SELECT name FROM datasets WHERE id=?",
                                    (dataset_id,)).fetchone()
            profile_row = conn.execute("SELECT profile_json FROM datasets WHERE id=?",
                                       (dataset_id,)).fetchone()
        profile = load_json(profile_row["profile_json"] if profile_row else None)
        for f in generate_findings(profile=None, quality=None, analysis=result,
                                   dataset_name=name_row["name"] if name_row else "dataset"):
            with db() as conn:
                conn.execute(
                    "INSERT INTO findings (id, dataset_id, analysis_id, model_id, "
                    "title, explanation, evidence_json, severity, recommendation, "
                    "limitations) VALUES (?,?,?,?,?,?,?,?,?,?)",
                    (new_id(), dataset_id, analysis_id, model_id, f["title"],
                     f["explanation"], json.dumps(f["evidence"]), f["severity"],
                     f["recommendation"], f["limitations"]))

        with db() as conn:
            conn.execute(
                "UPDATE analyses SET status='completed', progress=100, "
                "results_json=?, model_id=?, completed_at=datetime('now') WHERE id=?",
                (json.dumps(result, default=str), model_id, analysis_id))
    except MLInputError as e:
        with db() as conn:
            conn.execute("UPDATE analyses SET status='failed', error=?, "
                         "completed_at=datetime('now') WHERE id=?", (str(e), analysis_id))
    except Exception as e:
        with db() as conn:
            conn.execute("UPDATE analyses SET status='failed', error=?, "
                         "completed_at=datetime('now') WHERE id=?",
                         (f"{e} | {traceback.format_exc(limit=2)[-400:]}", analysis_id))


@router.post("/datasets/{dataset_id}/analysis/run")
def run_analysis(dataset_id: str, body: dict):
    task = body.get("task")
    if task not in ("classification", "regression", "clustering", "anomaly"):
        raise HTTPException(400, f"Unsupported task '{task}'.")
    config = body.get("config") or {}
    if task in ("classification", "regression") and not config.get("target"):
        raise HTTPException(400, "Supervised training requires a target column. "
                                 "Select one on the dataset page first.")
    if task in ("classification", "regression") and not config.get("algorithm"):
        raise HTTPException(400, "An algorithm must be selected.")
    analysis_id = new_id()
    with db() as conn:
        conn.execute(
            "INSERT INTO analyses (id, dataset_id, task_type, algorithm, "
            "target_column, config_json, status) VALUES (?,?,?,?,?,?,'queued')",
            (analysis_id, dataset_id, task, config.get("algorithm"),
             config.get("target"), str(config)))
    t = threading.Thread(target=_run_analysis_job,
                         args=(analysis_id, dataset_id, task, config), daemon=True)
    t.start()
    return {"analysis_id": analysis_id, "status": "queued"}


@router.get("/analyses")
def list_analyses(dataset_id: str | None = None, limit: int = 50):
    q = ("SELECT id, dataset_id, task_type, algorithm, target_column, status, "
         "progress, error, model_id, created_at, completed_at FROM analyses")
    args: list = []
    if dataset_id:
        q += " WHERE dataset_id=?"
        args.append(dataset_id)
    q += " ORDER BY created_at DESC LIMIT ?"
    args.append(limit)
    with db() as conn:
        rows = conn.execute(q, args).fetchall()
    return {"analyses": [row_to_dict(r) for r in rows]}


@router.get("/analysis/{analysis_id}")
def get_analysis(analysis_id: str):
    with db() as conn:
        row = conn.execute("SELECT * FROM analyses WHERE id=?",
                           (analysis_id,)).fetchone()
    if not row:
        raise HTTPException(404, "Analysis not found.")
    d = row_to_dict(row)
    d["results"] = load_json(d.pop("results_json"))
    d["config"] = load_json(d.pop("config_json"))
    return d
